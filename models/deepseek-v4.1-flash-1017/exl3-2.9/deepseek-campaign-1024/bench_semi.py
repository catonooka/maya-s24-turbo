#!/usr/bin/env python3
"""bench_semi.py - semi-repeat decode bench (:8080): the tier-B workload.

Real-world semi-repeats: structured output whose header recurs (JSON schemas, CSV
headers, code boilerplate, templated replies), bodies differing. Measures engine
decode t/s across 12 such asks (2 shapes x 6), compares vs the plain 3-bench.
Run twice: fresh record (tier B idle) vs warm record (tier B engaged).
"""
import time, requests, statistics

URL = "http://127.0.0.1:8080/v1/chat/completions"

def ask(prompt, max_tokens, timeout=900):
    t0 = time.time()
    r = requests.post(URL, json={"model": "deepseek-v4.1-flash",
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": max_tokens, "temperature": 0.0}, timeout=timeout)
    dt = time.time() - t0
    r.raise_for_status()
    j = r.json()
    return j["usage"]["completion_tokens"], dt

# Shape 1: CSV with a FIXED header block, varying rows (the header's prose preamble is
# ~60 tokens identical each time - tier-B match territory, the rows differ)
def csv_task(i):
    return (f"You are a reporting assistant. Output format is ALWAYS: a line 'REPORT v2.1 - "
            f"SEC {i}: <title>', then one line 'generated by unit {i%4}', then 8 CSV rows "
            f"'id,name,value' with ids {i*10}..{i*10+7} and made-up names/values. Keep the format exact.",
            300)

# Shape 2: code edit: same function header/docstring, body varies slightly
def code_task(i):
    return (f"Write a Python function 'process_batch_{i}(items: list) -> dict' with a standard "
            f"docstring (Args/Returns/Raises sections, always the same wording style), type hints, "
            f"3 asserts. Variant {i}: it should {'dedupe' if i%2 else 'sort'} items first and count "
            f"{'lengths' if i%3 else 'sums'}. Include the usual boilerplate comment header "
            f"'# stdlib processing module' at top.", 350)

TASKS = [csv_task(i) for i in range(6)] + [code_task(i) for i in range(6)]

def run(tag):
    tps_list = []
    for i, (p, mt) in enumerate(TASKS):
        ct, dt = ask(p, mt)
        tps = ct / dt
        tps_list.append(tps)
        print(f"  [{tag} {i+1:02d}] {ct} tok in {dt:.1f}s = {tps:5.2f} t/s")
    print(f"== {tag}: mean {statistics.mean(tps_list):.2f}  median {statistics.median(tps_list):.2f}")
    return tps_list

if __name__ == "__main__":
    run("semi")
